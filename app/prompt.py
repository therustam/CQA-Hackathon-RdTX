"""Prompt compiler: everything about criteria comes from the saved checklist.

The system prompt depends only on the checklist version (cached by the API across a batch);
the conversation goes into the user message.
"""
from app.transcript import first_operator_id, render

PREAMBLE = """Ты — эксперт по контролю качества клиентской поддержки брокерской компании Freedom Broker. Ты оцениваешь работу ОПЕРАТОРА в одном диалоге (чат или звонок) по чек-листу ниже и возвращаешь JSON по заданной схеме.

## Как устроены данные
- Каждая строка транскрипта: [mN] время роль: текст. mN — идентификатор реплики; ссылайся только на идентификаторы, которые есть в транскрипте.
- Роли: client — клиент; operator — оператор (оцениваем только его); bot — бот AIM или голосовое меню; system — системные события. Реплики бота и системные события — контекст, а не действия оператора. Приветствие бота не считается приветствием оператора.
- Чаты обычно идут так: клиент пишет боту, просит оператора, системное событие перевода на оператора, затем участок оператора. Оценивается участок оператора, но всё, что клиент сообщил боту до перевода и между переводом и первым ответом оператора, оператор должен учитывать.
- Системные события подсказывают ход диалога: перевод на оператора; подтверждение личности клиента; закрытие чата оператором (это не обрыв); обрыв связи, уход клиента из чата или завершение звонка клиентом (диалог прекратился не по воле оператора).
- Звонки — автоматическая расшифровка речи: возможны искажённые слова и имена, голосовое меню (IVR), нажатия клавиш. «[Имя скрыто]» означает, что имя было названо; «[Персональные данные скрыты]» и «[Данные идентификации скрыты]» — что данные были названы. Реплики оператора с пометкой «внутренняя консультация» — разговор с коллегой, пока клиент на удержании; клиент их не слышит.
- Пометка «(пауза ЧЧ:ММ)» перед ролью показывает долгую паузу перед репликой.

## Как отвечать
- Оцени КАЖДЫЙ критерий чек-листа ровно один раз, в порядке чек-листа; criterion_id — идентификатор критерия.
- applicable=false (N/A) — только если для критерия N/A разрешён и выполнено его условие; тогда na_reason — какое условие выполнено, answer=null, step=null. Если N/A не разрешён, applicable всегда true и na_reason=null.
- Критерий «Да/Нет» и флаг: answer — "yes" или "no", step=null.
- Шкала: step — ровно одна из перечисленных ступеней, answer=null.
- Флаг: при answer="yes" перечисли в subtypes идентификаторы подтипов; иначе subtypes=[]. Для остальных критериев subtypes=[].
- explanation: 1–3 предложения на русском: ответ, почему, на какие реплики опираешься. Цитаты — дословно на языке оригинала.
- evidence_ids: реплики, подтверждающие вывод (обычно 1–3). Если действие пропущено — реплики, где оно ожидалось. Для N/A — реплика, показывающая выполнение условия неприменимости.
- checked_range: [первый_id, последний_id] проверенного участка, если вывод основан на отсутствии действия; иначе [].
- confidence: уверенность от 0 до 1."""

TYPE_LABEL = {"binary": "Да/Нет", "scale": "шкала", "flag": "флаг без баллов (не входит в итог)"}
LANG = {"RU": "русский", "KZ": "казахский", "EN": "английский"}


def _criterion_block(c):
    head = f"### Критерий {c['id']}. {c['title']}\nТип: {TYPE_LABEL.get(c['type'], c['type'])}"
    if c["type"] != "flag":
        head += f", вес {c.get('weight', 0)}"
    na = (f"N/A допускается. Условие N/A: {c.get('na_condition') or 'см. правило'}" if c.get("na_allowed")
          else "N/A не допускается (applicable всегда true).")
    parts = [head, na, f"Правило: {c.get('rule', '')}"]
    if c.get("guidance"):
        parts.append(f"Как проверять: {c['guidance']}")
    if c["type"] == "scale":
        parts.append("Ступени шкалы:\n" + "\n".join(f"- {s['value']} — {s.get('label', '')}" for s in c["scale"]))
    if c.get("subtypes"):
        parts.append("Подтипы:\n" + "\n".join(f"- {s['id']} — {s.get('label', '')}" for s in c["subtypes"]))
    return "\n".join(parts)


def build_system(checklist):
    blocks = "\n\n".join(_criterion_block(c) for c in checklist["criteria"])
    rules = f"\n\n## Общие правила чек-листа\n{checklist['instructions']}" if checklist.get("instructions") else ""
    return f"{PREAMBLE}{rules}\n\n## Чек-лист: {checklist.get('name', '')}\n\n{blocks}"


def build_user(record, msgs, errors=None):
    channel = "звонок (расшифровка речи)" if record.get("channel") == "voice call" else "чат"
    lang = record.get("language", "")
    first = first_operator_id(msgs)
    text = (f"Диалог {record.get('conversation_id')}. Канал: {channel}. Язык диалога по данным: "
            f"{LANG.get(lang, lang)}.\n"
            f"Первая реплика оператора: {first or 'нет — оператор в диалоге не отвечал'}.\n\n"
            f"Транскрипт:\n{render(msgs)}")
    if errors:
        text += ("\n\nПредыдущий ответ отклонён проверкой:\n- " + "\n- ".join(errors)
                 + "\nИсправь ошибки и верни полный JSON по всем критериям заново.")
    return text
